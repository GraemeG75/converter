export function t(key: keyof UIStrings, lang: SupportedLanguage): string {
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return dict[key] || UI_TRANSLATIONS.en[key] || String(key);
}

export function getCategoryTranslation(categoryId: string, lang: SupportedLanguage): { name: string; description: string } {
  const langCats = CATEGORY_TRANSLATIONS[lang] || CATEGORY_TRANSLATIONS.en;
  if (langCats[categoryId]) {
    return langCats[categoryId];
  }
  return CATEGORY_TRANSLATIONS.en[categoryId] || { name: categoryId, description: '' };
}

export function getUnitNameTranslation(unitId: string, fallbackName: string, lang: SupportedLanguage): string {
  const langUnits = UNIT_NAME_TRANSLATIONS[lang] || UNIT_NAME_TRANSLATIONS.en;
  if (langUnits[unitId]) {
    return langUnits[unitId];
  }
  return fallbackName;
}
